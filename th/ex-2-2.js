/*
เรามี Array ages ซึ่งบรรจุอายุ
ให้เขียน Algorithm ที่นำ ages มาตรวจสอบว่ามีคนอายุน้อยกว่า 18 ปีหรือไม่
    - หากพบให้แสดงข้อความ "พบคนอายุน้อยกว่า 18" บนหน้าจอ
*/

const ages = [25, 32, 17, 40, 15];

// Start coding here

// กระบวนการ:
// - การแสดงผลลัพธ์
// - การเปรียบเทียบ
// - If-Else
// - Loop
// ขั้นตอน:
// 1. Loop ผ่านสมาชิกแต่ละตัวใน ages
//    <ในการวนแต่ละครั้ง ให้ใช้ If-Else
//       <ถ้าสมาชิกตัวนั้น น้อยกว่า 18 ให้แสดงคำว่า "พบคนอายุน้อยกว่า 18">>

for (let age of ages) {
  if (age < 18) {
    console.log("พบคนอายุน้อยกว่า 18");
  }
}
